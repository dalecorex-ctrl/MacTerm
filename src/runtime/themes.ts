function hexToRgb(hex: string): [number, number, number] | null {
  const clean = hex.trim().replace(/^#/, '');
  if (!/^[0-9a-fA-F]{6}$/.test(clean)) return null;
  return [
    parseInt(clean.slice(0, 2), 16),
    parseInt(clean.slice(2, 4), 16),
    parseInt(clean.slice(4, 6), 16),
  ];
}

export function getProfileById(
  id: string,
  customTheme?: { background: string; foreground: string; cursor: string; accent: string },
): TerminalProfile {
  if (id === 'custom') {
    const theme = customTheme ?? {
      background: '#141b22',
      foreground: '#e2eff3',
      cursor: '#56d4dd',
      accent: '#3b82f6',
    };
    const rgb = hexToRgb(theme.background);
    const luma = rgb ? 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2] : 24;
    const isLight = luma > 160;
    const titlebarRgb = rgb
      ? rgb.map((c) => (isLight ? Math.max(0, c - 14) : Math.min(255, c + 10)))
      : [20, 27, 34];

    return {
      id: 'custom',
      name: 'Custom Theme',
      description: 'User-defined custom terminal palette.',
      isLight,
      windowBg: rgb ? `rgba(${rgb[0]}, ${rgb[1]}, ${rgb[2]}, 0.94)` : theme.background,
      titlebarBg: `rgba(${titlebarRgb[0]}, ${titlebarRgb[1]}, ${titlebarRgb[2]}, 0.96)`,
      xterm: {
        background: '#00000000',
        foreground: theme.foreground,
        cursor: theme.cursor,
        cursorAccent: theme.background,
        selectionBackground: `${theme.accent}40`,
        black: '#111111',
        red: '#FF5555',
        green: '#50FA7B',
        yellow: '#F1FA8C',
        blue: theme.accent,
        magenta: '#FF79C6',
        cyan: '#8BE9FD',
        white: theme.foreground,
        brightBlack: '#6272A4',
        brightRed: '#FF6E6E',
        brightGreen: '#69FF94',
        brightYellow: '#FFFFA5',
        brightBlue: theme.accent,
        brightMagenta: '#FF92DF',
        brightCyan: '#A4FFFF',
        brightWhite: '#FFFFFF',
      },
    };
  }
  return TERMINAL_PROFILES.find((p) => p.id === id) ?? TERMINAL_PROFILES[0];
}
